// Bundle the game's IPvGO rules and AI (bitburner-src) into servers/home/go-engine.js for go.js's search.
// usage: node tools/go-engine/build.mjs   (BITBURNER_SRC defaults to ~/Repos/bitburner-src)
import { build } from "esbuild";
import path from "path";
import os from "os";
import { fileURLToPath } from "url";
const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(process.env.BITBURNER_SRC ?? path.join(os.homedir(), "Repos/bitburner-src"), "src");
const keep = [/\/Go\/(Types|Constants|Enums)\.ts$/, /\/Go\/boardState\/(boardState|offlineNodes)\.ts$/, /\/Go\/boardAnalysis\//, /\/Casino\/RNG\.ts$/];
const stubPlugin = {
  name: "stubs",
  setup(b) {
    b.onResolve({ filter: /^@enums$/ }, () => ({ path: path.join(here, "stub-enums.ts") }));
    b.onResolve({ filter: /^@player$/ }, () => ({ path: path.join(here, "stub-player.ts") }));
    b.onResolve({ filter: /^SRC\// }, (a) => ({ path: path.join(src, a.path.slice(4)) + ".ts" }));
    b.onResolve({ filter: /^\.\.?\// }, (a) => {
      if (!a.importer.startsWith(src)) return undefined;
      const p = path.resolve(path.dirname(a.importer), a.path);
      if (p.endsWith("/utils/Utility")) return { path: path.join(here, "stub-utility.ts") };
      if (p.endsWith("/Go/Go")) return { path: path.join(here, "stub-go.ts") };
      const file = p + ".ts";
      if (keep.some((re) => re.test(file))) return { path: file };
      return { path: path.join(here, "stub-any.js") };
    });
  },
};
await build({
  entryPoints: [path.join(here, "entry.ts")],
  bundle: true,
  format: "esm",
  target: "es2022",
  outfile: path.join(here, "../../servers/home/go-engine.js"),
  plugins: [stubPlugin],
  banner: { js: "// GENERATED by tools/go-engine/build.mjs from bitburner-src (IPvGO rules and AI). Do not edit.\n/* eslint-disable */" },
  logLevel: "warning",
});
console.log("built servers/home/go-engine.js");
